"""Generate the explicit read-only S05 source queries from the dataset registry.

``python tools/write_source_queries.py`` writes ``queries/source_inputs/*.sql``,
``queries/discovery/*.sql`` and the FOCUS_FN supplemental readers.
``tests/integration/test_source_scope.py`` checks that the committed files
match the generator, so projections cannot drift from the registry.
"""
from __future__ import annotations

import sys
from pathlib import Path

APP_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(APP_ROOT))

from focus.data.datasets import DATASETS  # noqa: E402
from focus.data.discovery import FN_COLLISION_QUERY, SCHEMA_REFERENCE_QUERY  # noqa: E402

HEADER = "-- Generated by tools/write_source_queries.py from focus/data/datasets.py. Read-only; explicit projection (S05).\n"

SPECIAL_PREDICATES = {
    "cday_op_plan": "WHERE IS_ACTIVE=1",
    "cs_windows": "WHERE IS_ACTIVE=1",
}


def render(name: str) -> str:
    spec = DATASETS[name]
    cols = ",".join(spec.columns)
    if name == "master_task_list":
        prefixed = ",".join(f"m.{c}" for c in spec.columns)
        return (
            HEADER
            + "-- Complete broad WIP/anchor census: all statuses (including COMPLETE anchors) on every line with any non-COMPLETE work.\n"
            + "WITH WipLines AS (\n SELECT DISTINCT LINE_NUMBER FROM WEB_APP.FOCUS_MASTER_TASK_LIST\n WHERE SHOP_ORDER_STATUS <> 'COMPLETE'\n)\n"
            + f"SELECT {prefixed}\nFROM WEB_APP.FOCUS_MASTER_TASK_LIST m\nJOIN WipLines w ON w.LINE_NUMBER=m.LINE_NUMBER\n"
            + "ORDER BY m.LINE_NUMBER,m.SHOP_ORDER_IDENTIFIER;\n"
        )
    predicate = SPECIAL_PREDICATES.get(name)
    body = f"SELECT {cols}\nFROM {spec.source_object}"
    if predicate:
        body += f" {predicate}"
    return HEADER + body + ";\n"


SUPPLEMENTAL_READERS = {
    "queries/workforce/read_team_inference.sql": (
        HEADER
        + "-- SQL-owned team inference output (S06 FOCUS_FN_TeamInference) for this scope's head source run.\n"
        "-- Bound parameter (pymssql positional placeholder): ScopeKey.\n"
        "SELECT CONVERT(varchar(40), ti.RunId) AS RUN_ID, ti.PersonKey AS PERSON_KEY, ti.InferredTeam AS INFERRED_TEAM,\n"
        " ti.WindowStartUtc AS WINDOW_START_UTC, ti.WindowEndUtc AS WINDOW_END_UTC, ti.EvidenceCount AS EVIDENCE_COUNT,\n"
        " ti.EffortMinutes AS EFFORT_MINUTES, ti.TopShare AS TOP_SHARE,\n"
        " JSON_VALUE(CONVERT(nvarchar(max), ti.EvidencePayload), '$.runner_up_team') AS RUNNER_UP_TEAM,\n"
        " TRY_CONVERT(int, JSON_VALUE(CONVERT(nvarchar(max), ti.EvidencePayload), '$.runner_up_count')) AS RUNNER_UP_COUNT,\n"
        " ti.IsTie AS IS_TIE, ti.Basis AS BASIS, ti.AlgorithmVersion AS ALGORITHM_VERSION,\n"
        " TRY_CONVERT(datetime2(6), JSON_VALUE(CONVERT(nvarchar(max), ti.EvidencePayload), '$.first_evidence_utc')) AS FIRST_EVIDENCE_UTC,\n"
        " TRY_CONVERT(datetime2(6), JSON_VALUE(CONVERT(nvarchar(max), ti.EvidencePayload), '$.last_evidence_utc')) AS LAST_EVIDENCE_UTC\n"
        "FROM WEB_APP.FOCUS_FN_TeamInference ti\n"
        "WHERE ti.RunId = (SELECT h.RunId FROM WEB_APP.FOCUS_FN_SourceHead h WHERE h.ScopeKey = %s);\n"
    ),
    "queries/durations/read_clock_observations.sql": (
        HEADER
        + "-- Raw clock intervals (S06 FOCUS_FN_ClockObservation) for this scope's head source run.\n"
        "-- Bound parameter (pymssql positional placeholder): ScopeKey.\n"
        "SELECT co.SourceEventKey AS SOURCE_EVENT_KEY, co.LineNumber AS LINE_NUMBER, co.NativeSoi AS NATIVE_SOI,\n"
        " co.PersonKey AS PERSON_KEY, co.EpisodeKey AS EPISODE_KEY, co.Team AS TEAM, co.ReworkClass AS REWORK_CLASS,\n"
        " co.StartUtc AS START_UTC, co.EndUtc AS END_UTC, co.SourceRevision AS SOURCE_REVISION, co.IsVoided AS IS_VOIDED\n"
        "FROM WEB_APP.FOCUS_FN_ClockObservation co\n"
        "WHERE co.RunId = (SELECT h.RunId FROM WEB_APP.FOCUS_FN_SourceHead h WHERE h.ScopeKey = %s);\n"
    ),
}


def contract_documents() -> dict[str, str]:
    import json

    from focus.data.discovery import CONTRACTS, CONTRACTS_SHA, ECONOMICS_FOREIGN_KEYS

    contracts = {
        "schema_version": 1,
        "source": "FOCUS_FROM_NOTHING_MASTER.txt S04 (SQL Server MCP read-only verification 2026-10-27, SQL-D-22D10090/SHARED)",
        "contracts_sha256": CONTRACTS_SHA,
        "tables": {
            name: {"primary_key": list(t.primary_key), "columns": [c.render() for c in t.columns]}
            for name, t in sorted(CONTRACTS.items())
        },
        "economics_foreign_keys": [list(fk) for fk in ECONOMICS_FOREIGN_KEYS],
    }
    projections = {
        "schema_version": 1,
        "datasets": {
            name: {"kind": spec.kind, "source_object": spec.source_object, "columns": list(spec.columns),
                   "required_for_run": spec.required_for_run, "capabilities": list(spec.capabilities),
                   "cutoff_column": spec.cutoff_column, "description": spec.description}
            for name, spec in DATASETS.items()
        },
    }
    return {
        "fixtures/source_contracts/s04_contracts.json": json.dumps(contracts, indent=1, sort_keys=True) + "\n",
        "fixtures/source_contracts/dataset_projections.json": json.dumps(projections, indent=1, sort_keys=True) + "\n",
    }


def expected_files() -> dict[str, str]:
    files: dict[str, str] = dict(contract_documents())
    for name, spec in DATASETS.items():
        if spec.kind == "SOURCE":
            files[spec.query_file] = render(name)
    files["queries/discovery/schema_reference.sql"] = HEADER + SCHEMA_REFERENCE_QUERY + ";\n"
    files["queries/discovery/fn_collisions.sql"] = HEADER + FN_COLLISION_QUERY + ";\n"
    files.update(SUPPLEMENTAL_READERS)
    return files


def main() -> int:
    for relative, text in expected_files().items():
        path = APP_ROOT / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    print(f"wrote {len(expected_files())} query files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
