-- P10 readiness: buyoff plan versus inspection counts per job (read-only). Counts never locate IP holds:
-- a job with IN_PROCESS_QUALITY_INSP > 0 needs sourced hold points (supplemental inspection_holds) or it is
-- blocked for executable QA; counts that disagree with the buyoff plan are reported, never reconciled silently.
SELECT b.LINE_NUMBER, b.SHOP_ORDER_IDENTIFIER, b.SHOP_ORDER_STATUS,
       b.FINAL_QUALITY_INSP, b.IN_PROCESS_QUALITY_INSP, b.MANUFACTURING_INSP, b.QUALITY_INSP, b.CC_INSP, b.ODAUNITMEMBER_INSP, b.PARTNER_QT_INSP,
       c.FINAL_QUALITY_INSPECTIONS, c.IN_PROCESS_QUALITY_INSPECTIONS,
       CASE WHEN c.SHOP_ORDER_IDENTIFIER IS NULL THEN 'NO_COUNTS'
            WHEN c.FINAL_QUALITY_INSPECTIONS <> c.FINAL_MAX OR c.IN_PROCESS_QUALITY_INSPECTIONS <> c.IN_PROCESS_MAX THEN 'COUNT_ROWS_CONFLICT'
            WHEN COALESCE(b.FINAL_QUALITY_INSP, 0) <> c.FINAL_QUALITY_INSPECTIONS
              OR COALESCE(b.IN_PROCESS_QUALITY_INSP, 0) <> c.IN_PROCESS_QUALITY_INSPECTIONS THEN 'COUNTS_DISAGREE'
            ELSE 'CONSISTENT' END AS COUNT_CHECK,
       CASE WHEN COALESCE(b.IN_PROCESS_QUALITY_INSP, 0) > 0 THEN 'HOLD_LOCATIONS_REQUIRED' ELSE 'NONE' END AS IP_HOLD_REQUIREMENT
FROM WEB_APP.FOCUS_BUYOFF_PLAN b
LEFT JOIN (
    -- FOCUS_INSPECTION_COUNTS has no key: aggregate so duplicate rows cannot multiply jobs, and flag disagreement
    SELECT LINE_NUMBER, SHOP_ORDER_IDENTIFIER, COUNT_BIG(*) AS COUNT_ROWS,
           MIN(FINAL_QUALITY_INSPECTIONS) AS FINAL_QUALITY_INSPECTIONS, MAX(FINAL_QUALITY_INSPECTIONS) AS FINAL_MAX,
           MIN(IN_PROCESS_QUALITY_INSPECTIONS) AS IN_PROCESS_QUALITY_INSPECTIONS, MAX(IN_PROCESS_QUALITY_INSPECTIONS) AS IN_PROCESS_MAX
    FROM WEB_APP.FOCUS_INSPECTION_COUNTS
    GROUP BY LINE_NUMBER, SHOP_ORDER_IDENTIFIER
) c ON c.LINE_NUMBER = b.LINE_NUMBER AND c.SHOP_ORDER_IDENTIFIER = b.SHOP_ORDER_IDENTIFIER
ORDER BY b.LINE_NUMBER, b.SHOP_ORDER_IDENTIFIER;
