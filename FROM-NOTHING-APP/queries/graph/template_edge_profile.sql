-- P09 readiness: template relationship vocabulary, hard flags, signed lags and self edges (read-only).
-- Unsupported types or unknown hard flags quarantine the affected successor; negative OFFSET_MINUTES are kept.
SELECT d.RELATIONSHIP_TYPE, d.IS_HARD,
       COUNT_BIG(*) AS EDGES,
       SUM(CASE WHEN d.OFFSET_MINUTES < 0 THEN 1 ELSE 0 END) AS NEGATIVE_LAGS,
       SUM(CASE WHEN d.OFFSET_MINUTES IS NULL THEN 1 ELSE 0 END) AS NULL_LAGS,
       SUM(CASE WHEN d.PREDECESSOR_SOI = d.SUCCESSOR_SOI THEN 1 ELSE 0 END) AS SELF_EDGES,
       SUM(CASE WHEN d.PRED_MINOR_MODEL IS NULL OR d.SUC_MINOR_MODEL IS NULL THEN 1 ELSE 0 END) AS MODEL_EFFECTIVITY_MISSING,
       MAX(d.LOAD_TIMESTAMP) AS LATEST_LOAD
FROM WEB_APP.FOCUS_PNET_DAG d
GROUP BY d.RELATIONSHIP_TYPE, d.IS_HARD
ORDER BY d.RELATIONSHIP_TYPE, d.IS_HARD;
