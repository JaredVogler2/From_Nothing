-- P09 readiness: same-line rework links whose parent is missing, reversed or two-level (read-only).
-- Unresolved or cyclic linkage quarantines the child and its root; nothing is guessed from SOI prefixes.
SELECT r.LINE_NUMBER, r.CHILD_SOI, r.PARENT_SOI, r.CHILD_STATUS,
       CASE WHEN p.SHOP_ORDER_IDENTIFIER IS NULL THEN 1 ELSE 0 END AS PARENT_NOT_IN_MASTER,
       CASE WHEN rr.CHILD_SOI IS NOT NULL THEN 1 ELSE 0 END AS PARENT_IS_ITSELF_REWORK,
       CASE WHEN rev.CHILD_SOI IS NOT NULL THEN 1 ELSE 0 END AS REVERSED_PAIR,
       r.SNAPSHOT_TS
FROM WEB_APP.NEO_GRAPH_REWORK r
LEFT JOIN (SELECT DISTINCT m.LINE_NUMBER, m.SHOP_ORDER_IDENTIFIER FROM WEB_APP.FOCUS_MASTER_TASK_LIST m) p
       ON p.LINE_NUMBER = r.LINE_NUMBER AND p.SHOP_ORDER_IDENTIFIER = r.PARENT_SOI
LEFT JOIN WEB_APP.NEO_GRAPH_REWORK rr ON rr.LINE_NUMBER = r.LINE_NUMBER AND rr.CHILD_SOI = r.PARENT_SOI
LEFT JOIN WEB_APP.NEO_GRAPH_REWORK rev ON rev.LINE_NUMBER = r.LINE_NUMBER AND rev.CHILD_SOI = r.PARENT_SOI AND rev.PARENT_SOI = r.CHILD_SOI
ORDER BY r.LINE_NUMBER, r.CHILD_SOI;
