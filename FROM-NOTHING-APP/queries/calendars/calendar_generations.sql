-- P08 readiness: active per-line calendar generations, dense bounds and holes (read-only, explicit projection).
-- More than one active LOAD_ID on a line is a CALENDAR_GENERATION_CONFLICT unless the producer approves a
-- selector (calendar.generation_selector); holes inside the bounds block those dates (no weekday fallback).
WITH Active AS (
    SELECT c.LINE_NUMBER, c.LOAD_ID, c.CALENDAR_DATE, c.DAY_STATUS
    FROM WEB_APP.FOCUS_CDAY_OP_PLAN c
    WHERE c.IS_ACTIVE = 1
), PerLoad AS (
    SELECT LINE_NUMBER, LOAD_ID, MIN(CALENDAR_DATE) AS MIN_DATE, MAX(CALENDAR_DATE) AS MAX_DATE,
           COUNT(DISTINCT CALENDAR_DATE) AS DISTINCT_DATES, COUNT_BIG(*) AS ROW_COUNT,
           SUM(CASE WHEN DAY_STATUS = 'WORKING' THEN 1 ELSE 0 END) AS WORKING_ROWS,
           SUM(CASE WHEN DAY_STATUS IN ('WEEKEND', 'NONWORKING') THEN 1 ELSE 0 END) AS NONWORKING_ROWS,
           SUM(CASE WHEN DAY_STATUS IS NULL OR DAY_STATUS NOT IN ('WORKING', 'WEEKEND', 'NONWORKING') THEN 1 ELSE 0 END) AS UNKNOWN_STATUS_ROWS
    FROM Active
    GROUP BY LINE_NUMBER, LOAD_ID
), Conflicts AS (
    SELECT LINE_NUMBER, LOAD_ID, COUNT(*) AS CONFLICTING_DATES
    FROM (SELECT LINE_NUMBER, LOAD_ID, CALENDAR_DATE FROM Active GROUP BY LINE_NUMBER, LOAD_ID, CALENDAR_DATE
          HAVING COUNT(DISTINCT COALESCE(DAY_STATUS, N'?')) > 1) d
    GROUP BY LINE_NUMBER, LOAD_ID
)
SELECT p.LINE_NUMBER, p.LOAD_ID, p.MIN_DATE, p.MAX_DATE, p.DISTINCT_DATES,
       DATEDIFF(day, p.MIN_DATE, p.MAX_DATE) + 1 - p.DISTINCT_DATES AS HOLES_INSIDE_BOUNDS,
       p.ROW_COUNT, p.WORKING_ROWS, p.NONWORKING_ROWS, p.UNKNOWN_STATUS_ROWS, COALESCE(c.CONFLICTING_DATES, 0) AS CONFLICTING_DATES,
       COUNT(*) OVER (PARTITION BY p.LINE_NUMBER) AS ACTIVE_GENERATIONS_ON_LINE
FROM PerLoad p
LEFT JOIN Conflicts c ON c.LINE_NUMBER = p.LINE_NUMBER AND c.LOAD_ID = p.LOAD_ID
ORDER BY p.LINE_NUMBER, p.LOAD_ID;
